export function getAreaBySlug(slug: string): LocalArea | undefined {
  return LOCAL_AREAS.find((a) => a.slug === slug);
}

export function getNearbyAreaLinks(area: LocalArea): LocalArea[] {
  const byName = new Map(LOCAL_AREAS.map((a) => [a.name, a]));
  const linked: LocalArea[] = [];
  for (const name of area.nearby) {
    const match = byName.get(name);
    if (match && match.slug !== area.slug) linked.push(match);
  }

  const rest = LOCAL_AREAS.filter(
    (a) => a.slug !== area.slug && !linked.some((l) => l.slug === a.slug),
  );

  return [...linked, ...rest].slice(0, 10);
}
