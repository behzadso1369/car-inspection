function DataTable({
  headers,
  rows,
}: {
  headers: [string, string, string];
  rows: [string, string, string][];
}) {
  return (
    <div className="mt-5 overflow-x-auto rounded-2xl border border-[#E8ECF4]">
      <table className="w-full min-w-[640px] border-collapse text-right text-sm">
        <thead className="bg-[#EEF2FD] text-[#101117]">
          <tr>
            {headers.map((header) => (
              <th key={header} scope="col" className="px-4 py-3 font-bold">
                {header}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className="divide-y divide-[#E8ECF4] text-[#55565A]">
          {rows.map((row) => (
            <tr key={row[0]}>
              <th scope="row" className="bg-white px-4 py-3 text-[#101117]">
                {row[0]}
              </th>
              <td className="bg-white px-4 py-3 leading-7">{row[1]}</td>
              <td className="bg-white px-4 py-3 leading-7">{row[2]}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

