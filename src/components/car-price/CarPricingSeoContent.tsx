function ContentTable({
  headers,
  rows,
}: {
  headers: string[];
  rows: string[][];
}) {
  return (
    <div className="mt-5 overflow-x-auto rounded-2xl border border-[#E8ECF4]">
      <table className="w-full min-w-[640px] border-collapse text-right text-sm">
        <thead className="bg-[#F2F5FF] text-[#101117]">
          <tr>
            {headers.map((header) => (
              <th key={header} scope="col" className="px-4 py-3 font-extrabold">
                {header}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className="divide-y divide-[#E8ECF4]">
          {rows.map((row) => (
            <tr key={row.join("-")} className="bg-white">
              {row.map((cell, index) => (
                <td
                  key={`${row[0]}-${cell}`}
                  className={`px-4 py-3 leading-7 text-[#55565A] ${
                    index === 0 ? "font-bold text-[#101117]" : ""
                  }`}
                >
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

